// Bundles worklet.js and the engine modules it imports into one classic
// script: worklet.bundle.js (an AudioWorklet cannot resolve imports).
// Usage: node tools/build.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundleModules, wrapIife } from './lib.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { code, files } = bundleModules(root, ['worklet.js']);
const out = '// GENERATED by tools/build.mjs - do not edit. Source: engine/*.js + worklet.js\n' + wrapIife(code);
writeFileSync(join(root, 'worklet.bundle.js'), out);
console.log(`worklet.bundle.js: ${(out.length / 1024).toFixed(1)} KiB from ${files.length} files`);
